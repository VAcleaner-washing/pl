import fs from 'node:fs';
import path from 'node:path';

const root=process.cwd();
const read=rel=>fs.readFileSync(path.join(root,rel),'utf8');
const write=(rel,value)=>fs.writeFileSync(path.join(root,rel),value);
const walk=dir=>fs.readdirSync(dir,{withFileTypes:true}).flatMap(entry=>['.git','dist','node_modules'].includes(entry.name)?[]:entry.isDirectory()?walk(path.join(dir,entry.name)):[path.join(dir,entry.name)]);

// Address-provider repair must not change the established local delivery zone:
// Poltava, Rozsoshentsi, Shcherbani and Horbanivka all use the 250 UAH tariff.
for(const rel of ['assets/address-autocomplete.js','assets/public-booking-slots.js','assets/admin-v250.js','assets/booking-funnel-analytics.js']){
  let value=read(rel);
  value=value.split("localSettlements:['Полтава']").join("localSettlements:['Полтава','Розсошенці','Щербані','Горбанівка']");
  value=value.split('250 грн — Полтава · передмістя — від 350 грн; далі тариф залежить від відстані.')
    .join('250 грн — Полтава, Розсошенці, Щербані, Горбанівка · інше передмістя — від 350 грн.');
  value=value.split('${pricing.local} грн · Полтава.').join('${pricing.local} грн · Полтава / Розсошенці / Щербані / Горбанівка.');
  write(rel,value);
}

