import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8');
const js=read('assets/booking-hardening-v4144.js');
const css=read('assets/public-booking.css');
const pkg=JSON.parse(read('package.json'));
const release=JSON.parse(read('release.json'));
let pass=0,fail=[];
const ok=(name,cond)=>{if(cond){pass++;console.log('PASS',name)}else{fail.push(name);console.error('FAIL',name)}};
ok('release includes v4.2.42+ promo visibility contract',Number(release.build)>=4242&&pkg.version===release.version);
ok('promo toggle owns full friendly copy',js.includes('vx-promo-toggle__copy')&&js.includes('Введіть код — перевіримо знижку автоматично')&&js.includes('vx-promo-toggle__action'));
ok('promo toggle is full width',css.includes('.vx-promo-toggle{width:100%;min-height:60px'));
ok('promo is a full contact-grid row',css.includes('.booking-promo-field{position:relative;grid-column:1/-1}'));
ok('promo has visible gold-accent border and background',css.includes('rgba(151,103,47,.28)')&&css.includes('linear-gradient(180deg,#fffaf3 0%,#fbf6ee 100%)'));
ok('promo has explicit add action',css.includes('.vx-promo-toggle__action')&&js.includes("'Додати <i aria-hidden=\"true\">+</i>'"));
ok('promo open state is reflected in control copy',js.includes("open?'Сховати <i aria-hidden=\"true\">×</i>':'Додати <i aria-hidden=\"true\">+</i>'"));
ok('promo body does not use important override',!css.match(/booking-promo-field:not\(\.is-open\)[^}]*!important/));
ok('legacy hardening css no longer owns promo geometry',!read('assets/booking-hardening-v4144.css').includes('.vx-promo-toggle{'));
console.log(JSON.stringify({passed:pass,failed:fail,status:fail.length?'failed':'passed'}));
if(fail.length)process.exit(1);
