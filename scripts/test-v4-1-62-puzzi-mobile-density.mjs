import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=rel=>fs.readFileSync(path.join(root,rel),'utf8');
const release=JSON.parse(read('release.json'));
const pkg=JSON.parse(read('package.json'));
const css=read('assets/puzzi-seo.css');
const html=read('tekhnika/karcher-puzzi-8-1/index.html');
let failed=0,n=0;
const ok=(name,cond)=>{n++;if(cond)console.log(`OK   ${name}`);else{failed++;console.error(`FAIL ${name}`)}};
ok('release coherent',Number(release.build)>=4162&&String(pkg.version)===String(release.version));
ok('Puzzi mobile density layer exists',css.includes('v4.1.62 — mobile density pass for the long-form Puzzi landing page'));
ok('Puzzi hero media is shorter on phones',css.includes('.puzzi-hero-visual{min-height:340px}'));
ok('task zones use large horizontal snap cards',css.includes('.puzzi-zone-grid{display:grid;grid-template-columns:none;grid-auto-flow:column')&&css.includes('grid-auto-columns:minmax(278px,82vw)'));
ok('cleaning steps use horizontal snap cards',css.includes('.puzzi-cleaning-steps{display:grid;grid-template-columns:none;grid-auto-flow:column')&&css.includes('grid-auto-columns:minmax(286px,84vw)'));
ok('proof photography uses horizontal snap browsing',css.includes('.puzzi-proof-grid{display:grid;grid-template-columns:none;grid-auto-flow:column')&&css.includes('.puzzi-proof-grid a{height:330px;scroll-snap-align:start}'));
ok('terms remain fully visible',(html.match(/class="puzzi-term-grid"/g)||[]).length===1&&(html.match(/<section class="puzzi-terms"/g)||[]).length===1);
ok('all four task zones remain in markup',(html.match(/<div class="puzzi-zone-grid">[\s\S]*?<\/div>/)||[''])[0].match(/<article>/g)?.length===4);
ok('all five cleaning steps remain in markup',(html.match(/<div class="puzzi-cleaning-steps">[\s\S]*?<\/div>/)||[''])[0].match(/<article>/g)?.length===5);
ok('all three proof cards remain in markup',(html.match(/class="puzzi-proof-grid"/g)||[]).length===1&&html.includes('review-1.webp')&&html.includes('review-2.webp')&&html.includes('review-3.webp'));
ok('browser equipment density QA is wired',pkg.scripts['test:equipment-mobile-density']?.includes('equipment_mobile_density_qa.py'));
if(failed)process.exit(1);
console.log(`v4.1.62 Puzzi mobile density: ${n}/${n} OK`);
