import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=rel=>fs.readFileSync(path.join(root,rel),'utf8');
const release=JSON.parse(read('release.json'));
const pkg=JSON.parse(read('package.json'));
const css=read('assets/public-experience.css');
const html=read('index.html');
let failed=0,n=0;
const ok=(name,cond)=>{n++;if(cond)console.log(`OK   ${name}`);else{failed++;console.error(`FAIL ${name}`)}};
ok('release coherent',Number(release.build)>=4161&&String(pkg.version)===String(release.version));
ok('mobile density pass is present',css.includes('v4.1.61 — mobile homepage density pass'));
ok('mobile hero media is shortened',css.includes('.v21-hero-media,.v21-hero-media>img{height:350px!important;min-height:350px!important}'));
ok('solution photography stays editorial but compact',css.includes('.home-v21 .v21-solution-image{height:245px;min-height:245px}'));
ok('founder panel is compact on phone',css.includes('.home-v21 .v21-anna-media,.home-v21 .v21-anna-media img,.home-v21 .v21-anna-placeholder{height:340px;min-height:340px}'));
ok('reviews become a large snap carousel instead of three stacked screens',css.includes('scroll-snap-type:x mandatory')&&css.includes('flex:0 0 min(82vw,320px)'));
ok('mobile footer keeps two useful columns',read('assets/site-v400.css').includes('.home-v21 .v4-footer-grid{grid-template-columns:1fr 1fr!important}'));
ok('desktop package price rhythm survives',css.includes('.home-v21 .v21-package-grid>article>h3{height:178px;min-height:178px}'));
ok('homepage keeps all four task solutions',(html.match(/class="v21-solution"/g)||[]).length===4);
ok('homepage keeps all three packages',(html.match(/<article class="(?:is-featured)?">/g)||[]).length>=3&&html.includes('Глибоке очищення диванів і матраців')&&html.includes('Генеральне прибирання')&&html.includes('HOME RESET'));
ok('homepage keeps all three process visuals',(html.match(/<div class="v21-review-grid">[\s\S]*?<\/div>/)||[''])[0].includes('review-1.webp')&&html.includes('review-2.webp')&&html.includes('review-3.webp'));
ok('browser density QA is wired',pkg.scripts['test:home-mobile-density']?.includes('home_mobile_density_qa.py'));
if(failed)process.exit(1);
console.log(`v4.1.61 Mobile homepage density: ${n}/${n} OK`);
